// Writes the voice files of a directory (*.vce and *.cfg: compound files, read by the engine as they
// are) as a C source defining the table `voice_files` for voice-baked builds (vc_files_use).
//   mkvoices <dir> > voicedata_gen.c      (generated: Microsoft's voice data, never committed)
#include <dirent.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <strings.h>

static int want(const char *n) {
    size_t l = strlen(n);
    return l > 4 && (!strcasecmp(n + l - 4, ".vce") || !strcasecmp(n + l - 4, ".cfg"));
}
static int cmp(const void *a, const void *b) { return strcasecmp(*(char *const *)a, *(char *const *)b); }

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: mkvoices <dir> > out.c\n"); return 2; }
    DIR *d = opendir(argv[1]);
    if (!d) { perror(argv[1]); return 2; }
    char *names[64];
    int n = 0;
    struct dirent *de;
    while ((de = readdir(d)) && n < 64)
        if (want(de->d_name)) names[n++] = strdup(de->d_name);
    closedir(d);
    qsort(names, (size_t)n, sizeof *names, cmp);
    printf("// generated by port/mkvoices: Microsoft's voice files, do not commit\n#include \"crt_vc.h\"\n");
    for (int i = 0; i < n; i++) {
        char path[1024];
        snprintf(path, sizeof path, "%s/%s", argv[1], names[i]);
        FILE *f = fopen(path, "rb");
        if (!f) { perror(path); return 2; }
        fseek(f, 0, SEEK_END);
        long len = ftell(f);
        fseek(f, 0, SEEK_SET);
        unsigned char *buf = malloc((size_t)len);
        if (fread(buf, 1, (size_t)len, f) != (size_t)len) { perror(path); return 2; }
        fclose(f);
        // a string literal per 64 bytes: fast to compile, exactly `len` bytes (no terminator kept)
        printf("static const unsigned char file%d[%ld] =\n", i, len);
        for (long k = 0; k < len; k += 64) {
            printf("\"");
            for (long j = k; j < k + 64 && j < len; j++) printf("\\%o", buf[j]);
            printf("\"\n");
        }
        printf(";\n");
        free(buf);
    }
    printf("const VcFile voice_files[] = {\n");
    for (int i = 0; i < n; i++) printf("    { \"%s\", file%d, sizeof file%d },\n", names[i], i, i);
    printf("};\nconst int voice_nfiles = %d;\n", n);
    return 0;
}
