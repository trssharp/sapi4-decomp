// Writes the build-time image of msttssyn.dll's data (its .rdata and .data, and the list of pointer-
// holding dwords) as a C source defining `const DllBlob dll_baked`, for voice-baked builds.
//   mkimage <dir with msttssyn.dll> > dlldata_gen.c      (generated: Microsoft's data, never committed)
#include "dllimage.h"
#include <stdio.h>

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: mkimage <dir with msttssyn.dll> > out.c\n"); return 2; }
    char path[1024];
    snprintf(path, sizeof path, "%s/msttssyn.dll", argv[1]);
    if (!dll_image_load(path)) { fprintf(stderr, "cannot load %s\n", path); return 2; }
    DllBlob b = dll_image_blob();
    uint32_t keep[16];
    printf("// generated by port/mkimage from msttssyn.dll: do not commit\n#include \"dllimage.h\"\n");
    for (uint32_t i = 0; i < b.nsections; i++) {
        // trailing zeros are left out (the image is zero-filled)
        uint32_t n = b.sections[i].size;
        while (n && !b.sections[i].data[n - 1]) n--;
        printf("static const uint8_t sec%u[%u] = {", i, n ? n : 1);
        for (uint32_t k = 0; k < n; k++) printf("%s%u,", k % 32 ? "" : "\n", b.sections[i].data[k]);
        if (!n) printf("0");
        printf("\n};\n");
        keep[i] = n;
    }
    printf("static const DllBlobSection secs[%u] = {\n", b.nsections);
    for (uint32_t i = 0; i < b.nsections; i++) printf("    { %uu, %uu, sec%u },\n", b.sections[i].va, keep[i], i);
    printf("};\nstatic const uint32_t slots[%u] = {", b.nslots);
    for (uint32_t k = 0; k < b.nslots; k++) printf("%s%uu,", k % 16 ? "" : "\n", b.slots[k]);
    printf("\n};\nconst DllBlob dll_baked = { %uu, %uu, secs, %uu, slots };\n", b.image_size, b.nsections, b.nslots);
    return 0;
}
